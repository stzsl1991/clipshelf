struct Shortcut: Codable, Equatable {
    var key: String = "V"
    var control = true
    var option = true
    var command = false
    var shift = false
    static let codes: [String: UInt32] = ["A":0,"S":1,"D":2,"F":3,"H":4,"G":5,"Z":6,"X":7,"C":8,"V":9,"B":11,"Q":12,"W":13,"E":14,"R":15,"Y":16,"T":17,"1":18,"2":19,"3":20,"4":21,"6":22,"5":23,"9":25,"7":26,"8":28,"0":29,"O":31,"U":32,"I":34,"P":35,"L":37,"J":38,"K":40,"N":45,"M":46]
    var modifiers: UInt32 { (control ? UInt32(controlKey) : 0) | (option ? UInt32(optionKey) : 0) | (command ? UInt32(cmdKey) : 0) | (shift ? UInt32(shiftKey) : 0) }
    var display: String { (control ? "⌃" : "") + (option ? "⌥" : "") + (shift ? "⇧" : "") + (command ? "⌘" : "") + key }
}
final class Preferences {
    let defaults: UserDefaults
    static let defaultExcluded = ["com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "com.bitwarden.desktop", "com.lastpass.LastPass", "com.keepassium.KeePassium"]
    init(defaults: UserDefaults = .standard) { self.defaults = defaults }
    var shortcut: Shortcut {
        get { defaults.data(forKey: "shortcut").flatMap { try? JSONDecoder().decode(Shortcut.self, from: $0) } ?? Shortcut() }
        set { defaults.set(try? JSONEncoder().encode(newValue), forKey: "shortcut") }
    }
    var excluded: [String] { get { defaults.stringArray(forKey: "excluded") ?? Self.defaultExcluded } set { defaults.set(newValue, forKey: "excluded") } }
    var maxCount: Int { get { let n = defaults.integer(forKey: "maxCount"); return [100,500,1000,5000].contains(n) ? n : 1000 } set { defaults.set(newValue, forKey: "maxCount") } }
    var maxDays: Int { get { let n = defaults.integer(forKey: "maxDays"); return [1,7,30,90].contains(n) ? n : 30 } set { defaults.set(newValue, forKey: "maxDays") } }
    var limits: HistoryLimits { HistoryLimits(count: maxCount, days: maxDays) }
}
final class GlobalShortcut {
    private var hotKey: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private var generation: UInt32 = 0
    var action: (() -> Void)?
    init() {
        var event = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, event, context in
            guard let context = context, let event = event else { return OSStatus(eventNotHandledErr) }
            let instance = Unmanaged<GlobalShortcut>.fromOpaque(context).takeUnretainedValue()
            var id = EventHotKeyID()
            GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil, MemoryLayout<EventHotKeyID>.size, nil, &id)
            guard id.signature == 0x43534C46, id.id == instance.generation else { return OSStatus(eventNotHandledErr) }
            instance.action?(); return noErr
        }, 1, &event, Unmanaged.passUnretained(self).toOpaque(), &handler)
    }
    func register(_ shortcut: Shortcut) throws {
        guard let code = Shortcut.codes[shortcut.key], shortcut.control || shortcut.option || shortcut.command else {
            throw ShelfError.message("请选择一个字母或数字，并至少使用 Control、Option、Command 中的一个修饰键。")
        }
        let next = generation + 1
        var candidate: EventHotKeyRef?
        let status = RegisterEventHotKey(code, shortcut.modifiers, EventHotKeyID(signature: 0x43534C46, id: next), GetApplicationEventTarget(), 0, &candidate)
        guard status == noErr else { throw ShelfError.message("快捷键注册失败，可能已被系统或其他应用占用。请换一组快捷键。") }
        if let old = hotKey { UnregisterEventHotKey(old) }
        hotKey = candidate; generation = next
    }
    deinit { if let key = hotKey { UnregisterEventHotKey(key) }; if let handler = handler { RemoveEventHandler(handler) } }
}
final class ClipboardMonitor {
    static let ignoredTypes: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "net.antelle.keeweb", "de.petermaurer.TransientPasteboardType"]
    static let supported: [NSPasteboard.PasteboardType] = [.string, .URL, .rtf, .html, .png, .tiff, NSPasteboard.PasteboardType("public.jpeg")]
    static let ownType = NSPasteboard.PasteboardType("com.shulin.ClipShelf.restored")
    let pasteboard: NSPasteboard
    let store: HistoryStore
    let preferences: Preferences
    var paused = false { didSet { lastCount = pasteboard.changeCount; onStatus?() } }
    var sessionActive = true
    var onStatus: (() -> Void)?
    var onError: ((String) -> Void)?
    private(set) var status = "正在记录"
    private var lastCount: Int
    private var timer: Timer?
    private var observers: [NSObjectProtocol] = []
    init(store: HistoryStore, preferences: Preferences, pasteboard: NSPasteboard = .general) {
        self.store = store; self.preferences = preferences; self.pasteboard = pasteboard; lastCount = pasteboard.changeCount
    }
    func start() {
        timer = Timer(timeInterval: 0.2, repeats: true) { [weak self] _ in self?.tick() }
        RunLoop.main.add(timer!, forMode: .common)
        let center = NSWorkspace.shared.notificationCenter
        observers.append(center.addObserver(forName: NSWorkspace.sessionDidResignActiveNotification, object: nil, queue: .main) { [weak self] _ in self?.sessionActive = false })
        observers.append(center.addObserver(forName: NSWorkspace.sessionDidBecomeActiveNotification, object: nil, queue: .main) { [weak self] _ in
            self?.sessionActive = true; self?.lastCount = self?.pasteboard.changeCount ?? 0
        })
        observers.append(center.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in
            self?.lastCount = self?.pasteboard.changeCount ?? 0
            try? self?.store.prune()
        })
    }
    static func snapshot(_ pasteboard: NSPasteboard, maxBytes: Int) -> ClipPayload? {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return nil }
        let allTypes = Set(items.flatMap { $0.types.map { $0.rawValue } })
        guard allTypes.isDisjoint(with: ignoredTypes), !allTypes.contains(ownType.rawValue),
              !allTypes.contains(NSPasteboard.PasteboardType.fileURL.rawValue), !allTypes.contains("NSFilenamesPboardType") else { return nil }
        var size = 0
        var result: [ClipItem] = []
        for item in items {
            var representations: [Representation] = []
            for type in supported where item.types.contains(type) {
                guard let data = item.data(forType: type) else { continue }
                size += data.count
                guard size <= maxBytes else { return nil }
                representations.append(Representation(type: type.rawValue, data: data))
            }
            if !representations.isEmpty { result.append(ClipItem(representations: representations)) }
        }
        guard !result.isEmpty else { return nil }
        let payload = ClipPayload(items: result)
        guard payload.imageData != nil || payload.plainText != nil else { return nil }
        return payload
    }
    func tick(source: NSRunningApplication? = NSWorkspace.shared.frontmostApplication) {
        let current = pasteboard.changeCount
        guard current != lastCount else { return }
        lastCount = current
        guard !paused, sessionActive else { return }
        guard source?.bundleIdentifier != Bundle.main.bundleIdentifier || pasteboard.name != .general else { return }
        if let id = source?.bundleIdentifier, preferences.excluded.contains(id) { status = "已忽略排除应用的内容"; onStatus?(); return }
        guard let payload = Self.snapshot(pasteboard, maxBytes: store.limits.itemBytes) else {
            status = "已跳过敏感、文件或不支持的内容"; onStatus?(); return
        }
        guard pasteboard.changeCount == current else { lastCount = current; return }
        do {
            try store.insert(payload, source: source?.localizedName ?? "未知来源", bundleID: source?.bundleIdentifier)
            status = "正在记录"; onStatus?()
        } catch { status = "记录失败"; onError?(error.localizedDescription); onStatus?() }
    }
    func restore(_ payload: ClipPayload, plainText: Bool) throws {
        var objects: [NSPasteboardItem] = []
        if plainText {
            guard let text = payload.plainText else { throw ShelfError.message("这条内容没有可粘贴的纯文本。") }
            let item = NSPasteboardItem(); item.setString(text, forType: .string); item.setString("1", forType: Self.ownType); objects = [item]
        } else {
            objects = payload.items.map { value in
                let item = NSPasteboardItem()
                for rep in value.representations { item.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.type)) }
                item.setString("1", forType: Self.ownType); return item
            }
        }
        pasteboard.clearContents()
        guard pasteboard.writeObjects(objects) else { lastCount = pasteboard.changeCount; throw ShelfError.message("无法写入系统剪贴板，请重试。") }
        lastCount = pasteboard.changeCount
    }
    deinit { timer?.invalidate(); observers.forEach { NSWorkspace.shared.notificationCenter.removeObserver($0) } }
}
struct PasteDestination {
    let app: NSRunningApplication
    let focusedElement: AXUIElement?
    init(app: NSRunningApplication) {
        self.app = app
        self.focusedElement = Self.focus(in: app)
    }
    static func focus(in app: NSRunningApplication) -> AXUIElement? {
        guard AXIsProcessTrusted() else { return nil }
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(AXUIElementCreateApplication(app.processIdentifier), kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value = value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }
    func matchesCurrentFocus() -> Bool {
        guard let old = focusedElement else { return true }
        guard let current = Self.focus(in: app) else { return false }
        return CFEqual(old, current)
    }
}
